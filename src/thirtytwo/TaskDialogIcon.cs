namespace Windows;

/// <summary>
///  Specifies predefined task dialog main icons.
/// </summary>
public enum TaskDialogIcon
{
    /// <summary>
    ///  Warning icon.
    /// </summary>
    Warning = -1,

    /// <summary>
    ///  Error icon.
    /// </summary>
    Error = -2,

    /// <summary>
    ///  Information icon.
    /// </summary>
    Information = -3,

    /// <summary>
    ///  Shield icon.
    /// </summary>
    Shield = -4
}