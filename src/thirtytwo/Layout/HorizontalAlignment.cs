namespace Windows;

/// <summary>
///  Specifies horizontal placement of a child rectangle within available bounds.
/// </summary>
public enum HorizontalAlignment
{
    /// <summary>
    ///  Aligns the child rectangle to the left edge.
    /// </summary>
    Left,

    /// <summary>
    ///  Aligns the child rectangle to the right edge.
    /// </summary>
    Right,

    /// <summary>
    ///  Centers the child rectangle horizontally.
    /// </summary>
    Center
}